from datetime import date, datetime, timezone

from fastapi import HTTPException
from sqlalchemy import text
from sqlalchemy.orm import Session

from app.db.models import ReportVersion, User
from app.services.platform_settings_service import is_platform_admin_user
from app.services.subscription_service import latest_subscription, plan_access

FREE_ASSESSMENT_LIMIT = 5


def assessment_period() -> tuple[date, date]:
    now = datetime.now(timezone.utc).date()
    start = now.replace(day=1)
    end = date(now.year + (now.month == 12), now.month % 12 + 1, 1)
    return start, end


def assessment_usage(db: Session, user: User, *, tier: str, period: tuple[date, date] | None = None) -> dict:
    start, end = period or assessment_period()
    counts = db.execute(text("""
        SELECT count(*) FILTER (WHERE state = 'consumed') AS used,
               count(*) FILTER (WHERE state = 'reserved') AS reserved
        FROM assessment_quota_reservations
        WHERE user_id = :user_id AND period_start = :start
    """), {"user_id": user.id, "start": start}).mappings().one()
    limit = FREE_ASSESSMENT_LIMIT if tier == "free" else None
    used, reserved = counts["used"], counts["reserved"]
    return {
        "limit": limit,
        "used": used,
        "reserved": reserved,
        "remaining": max(0, limit - used - reserved) if limit is not None else None,
        "resets_at": f"{end.isoformat()}T00:00:00Z",
    }


def assessment_tier(db: Session, user: User) -> str:
    return plan_access(latest_subscription(db, user), platform_admin=is_platform_admin_user(db, user))["tier"]


def check_assessment_slot(db: Session, user: User, case_id, request_key: str, period: tuple[date, date]) -> ReportVersion | None:
    tier = assessment_tier(db, user)
    # The connector already holds this same lock during confirmation.
    db.execute(text("SELECT id FROM users WHERE id = :id FOR UPDATE"), {"id": user.id})
    existing = db.execute(text("""
        SELECT case_id, report_id, state FROM assessment_quota_reservations
        WHERE user_id = :user_id AND request_key = :key
    """), {"user_id": user.id, "key": request_key}).mappings().first()
    if existing:
        if existing["case_id"] != case_id:
            raise HTTPException(409, detail={"code": "assessment_request_conflict", "message": "This request key was already used for a different case."})
        if existing["state"] == "consumed":
            report = db.get(ReportVersion, existing["report_id"]) if existing["report_id"] else None
            if report is None:
                raise HTTPException(410, detail={"code": "assessment_removed", "message": "The report generated by this request was removed."})
            return report
        if existing["state"] == "reserved":
            raise HTTPException(409, detail={"code": "assessment_in_progress", "message": "This Assessment is already being generated. Retry to check its result."})
    usage = assessment_usage(db, user, tier=tier, period=period)
    if usage["remaining"] == 0:
        raise HTTPException(429, detail={
            "code": "assessment_quota_exhausted",
            "message": "Your monthly Assessment allowance is exhausted. Upgrade to Pro or wait for the reset.",
            "quota": usage,
        })
    return None


def reserve_assessment(db: Session, report: ReportVersion, request_key: str, start: date) -> None:
    db.execute(text("""
        INSERT INTO assessment_quota_reservations (user_id, request_key, case_id, report_id, period_start, state)
        VALUES (:user_id, :key, :case_id, :report_id, :start, 'reserved')
        ON CONFLICT (user_id, request_key) DO UPDATE
        SET report_id = EXCLUDED.report_id, period_start = EXCLUDED.period_start,
            state = 'reserved', updated_at = now()
        WHERE assessment_quota_reservations.state = 'released'
    """), {"user_id": report.created_by_user_id, "key": request_key, "case_id": report.case_id,
           "report_id": report.id, "start": start})


def settle_assessment(db: Session, report_id, *, succeeded: bool) -> None:
    db.execute(text("""
        UPDATE assessment_quota_reservations SET state = :state, updated_at = now()
        WHERE report_id = :report_id AND state = 'reserved'
    """), {"report_id": report_id, "state": "consumed" if succeeded else "released"})
